/** 카피에 입력에 없는 가짜 정보가 있는지 검사. 매칭 패턴 반환. */
export function findFakeClaims(text: string, allowedRaw: string): string[] {
  if (!text) return [];
  const matches: string[] = [];
  for (const re of FAKE_INFO_PATTERNS) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(text)) !== null) {
      const claim = m[0];
      // 입력 자유설명에 같은 문자열이 있으면 OK(사장님이 명시한 사실)
      if (!allowedRaw.includes(claim)) matches.push(claim);
    }
  }
  return matches;
}
